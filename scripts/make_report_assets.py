#!/usr/bin/env python3
"""Generate the numbers, table bodies and figures used by docs/report/main.tex.

Every figure in the paper is read from the saved evaluation runs, so a change
in a run directory is picked up by rebuilding rather than by retyping.

    uv run python scripts/make_report_assets.py \
        --main evaluation/results/post-freeze-fixes-frozen-real-20261120 \
        --noreplan evaluation/results/post-freeze-fixes-no-replan-20261120 \
        --ceiling docs/report/generated/ceiling_check_fixed.json \
        --spike docs/report/generated/spike_fixed_summary.csv
"""

from __future__ import annotations

import argparse
import csv
import json
from collections import OrderedDict
from pathlib import Path

import matplotlib
import numpy as np

matplotlib.use("Agg")
import matplotlib.pyplot as plt

CATEGORY_LABEL = OrderedDict(
    [
        ("filter", "filter"),
        ("group_aggregate", "group aggregate"),
        ("rank", "rank"),
        ("period_compare", "period compare"),
        ("trend", "trend"),
        ("segment_contribution", "contribution"),
        ("correlation", "correlation"),
        ("anomalies", "anomalies"),
        ("multistep", "multi-step"),
    ]
)


def load_run(path: Path) -> dict:
    return json.loads((path / "agent_eval.json").read_text(encoding="utf-8"))


def categories(questions_path: Path) -> dict[str, str]:
    return {q["id"]: q["category"] for q in json.loads(questions_path.read_text(encoding="utf-8"))}


def summarise(run: dict, cat_of: dict[str, str], reachable: set[str] | None = None) -> dict:
    """Per-category and overall counts. A question passes if any repeat matches the oracle."""
    attempts = run["runs"]
    by_q: dict[str, list[bool]] = {}
    for attempt in attempts:
        by_q.setdefault(attempt["question_id"], []).append(attempt["status"] == "passed")
    per_cat: dict[str, dict] = {
        c: {"n": 0, "q": 0, "a": 0, "at": 0, "base": 0, "reach": 0} for c in CATEGORY_LABEL
    }
    baseline = {row["question_id"]: bool(row["baseline_accuracy"]) for row in run["per_question"]}
    for qid, cat in cat_of.items():
        entry = per_cat[cat]
        entry["n"] += 1
        results = by_q.get(qid, [])
        entry["q"] += any(results)
        entry["a"] += sum(results)
        entry["at"] += len(results)
        entry["base"] += baseline.get(qid, False)
        if reachable is not None and qid in reachable:
            entry["reach"] += 1
    totals = {
        k: sum(c[k] for c in per_cat.values()) for k in ("n", "q", "a", "at", "base", "reach")
    }
    reach_passed = (
        sum(1 for qid in (reachable or set()) if any(by_q.get(qid, [])))
        if reachable is not None
        else None
    )
    agg = run["aggregate"]
    status = run["question_status_counts"]
    return {
        "per_cat": per_cat,
        "totals": totals,
        "calls": agg["total_llm_call_count"],
        "time_s": run["evaluation"]["total_time_s"],
        "timeouts": status.get("timeout", 0),
        "stages": agg["stage_timings"],
        "reach_passed": reach_passed,
        "failed_q": sorted(qid for qid in cat_of if not any(by_q.get(qid, []))),
        "settings": run["evaluation"],
    }


def macro(name: str, value) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}\n"


def write_numbers(out: Path, runs: dict[str, dict]) -> None:
    lines = ["% generated by scripts/make_report_assets.py; do not edit\n"]
    for tag, s in runs.items():
        t = s["totals"]
        lines += [
            macro(f"{tag}Q", t["q"]),
            macro(f"{tag}N", t["n"]),
            macro(f"{tag}A", t["a"]),
            macro(f"{tag}AT", t["at"]),
            macro(f"{tag}Calls", s["calls"]),
            macro(f"{tag}Minutes", f"{s['time_s'] / 60:.0f}"),
            macro(f"{tag}Timeouts", s["timeouts"]),
            macro(f"{tag}Failed", ", ".join(s["failed_q"])),
            macro(f"{tag}Pct", f"{100 * t['q'] / t['n']:.0f}"),
        ]
        if s.get("reach_passed") is not None:
            lines += [
                macro(f"{tag}ReachPassed", s["reach_passed"]),
                macro(f"{tag}Reach", t["reach"]),
            ]
        cfg = s["settings"]
        lines += [
            macro(f"{tag}RepairCap", cfg["max_repair_attempts"]),
            macro(f"{tag}CallCap", cfg["max_llm_calls_per_question"]),
            macro(f"{tag}Budget", f"{cfg['per_question_budget_s']:.0f}"),
        ]
        if "max_replans" in cfg:
            lines.append(macro(f"{tag}Replans", cfg["max_replans"]))
    (out / "numbers.tex").write_text("".join(lines), encoding="utf-8")


def write_category_table(out: Path, main: dict, noreplan: dict | None) -> None:
    """One row per category: questions passed by each run (one attempt per question) and the baseline."""
    rows = []
    for key, label in CATEGORY_LABEL.items():
        m = main["per_cat"][key]
        cells = [label, str(m["n"]), f"{m['q']}"]
        if noreplan is not None:
            cells.append(f"{noreplan['per_cat'][key]['q']}")
        cells.append(f"{m['base']}")
        rows.append(" & ".join(cells) + r" \\")
    mt = main["totals"]
    total = ["\\textbf{All}", str(mt["n"]), str(mt["q"])]
    if noreplan is not None:
        total.append(str(noreplan["totals"]["q"]))
    total.append(str(mt["base"]))
    body = "\n".join(rows) + "\n\\hline\n" + " & ".join(total) + r" \\" + "\n\\hline\n"
    (out / "tab_category_body.tex").write_text(body, encoding="utf-8")


def write_spike_table(out: Path, spike_csv: Path) -> None:
    """Model comparison rows from the spike summary (one attempt per question for every model)."""
    rows = []
    with spike_csv.open(encoding="utf-8", newline="") as handle:
        for row in csv.DictReader(handle):
            name = row["model"].split(" (")[0]
            rows.append(
                " & ".join(
                    [
                        f"\\texttt{{{name}}}".replace("_", "\\_"),
                        f"{row['questions_passed']}/{row['questions_total']}",
                        row["timeouts"],
                        row["no_score_shaped_answer"],
                        row["total_llm_calls"],
                    ]
                )
                + r" \\"
            )
    (out / "tab_spike_body.tex").write_text("\n".join(rows) + "\n\\hline\n", encoding="utf-8")


def write_time_figure(out: Path, main: dict, noreplan: dict | None) -> None:
    """Seconds per stage, replanning on versus off (repair prompts shown as their own stage)."""
    order = [
        ("plan_generation", "plan"),
        ("replanning", "replan"),
        ("repair", "repair"),
        ("answer_synthesis", "answer"),
        ("tool_execution", "tools"),
    ]

    def stage_values(stages: dict) -> list[float]:
        stages = dict(stages)
        stages["repair"] = sum(v for k, v in stages.items() if k.startswith("repair_attempt_"))
        return [stages.get(key, 0.0) for key, _ in order]

    labels = [lab for _, lab in order]
    plt.rcParams.update({"font.family": "serif", "font.size": 8})
    fig, ax = plt.subplots(figsize=(3.3, 2.0))
    positions = np.arange(len(labels))
    series = [("R1", stage_values(main["stages"]), "0.35")]
    if noreplan is not None:
        series.append(("R2", stage_values(noreplan["stages"]), "0.75"))
    height = 0.38
    top = max(max(v) for _, v, _ in series)
    for idx, (name, values, colour) in enumerate(series):
        offset = (idx - (len(series) - 1) / 2) * height
        bars = ax.barh(
            positions + offset,
            values,
            height,
            color=colour,
            edgecolor="black",
            linewidth=0.5,
            label=name,
        )
        for bar, value in zip(bars, values):
            ax.text(
                bar.get_width() + top * 0.01,
                bar.get_y() + bar.get_height() / 2,
                f"{value:,.0f}",
                va="center",
                fontsize=6.5,
            )
    ax.set_yticks(positions, labels)
    ax.invert_yaxis()
    ax.set_xlabel("seconds, summed over the 20 question runs")
    ax.set_xlim(0, top * 1.2)
    ax.legend(frameon=False, loc="lower right")
    for spine in ("top", "right"):
        ax.spines[spine].set_visible(False)
    fig.tight_layout(pad=0.4)
    fig.savefig(out / "figures" / "fig_stage_time.pdf")
    plt.close(fig)


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--main", type=Path, required=True, help="run with replanning on")
    parser.add_argument("--noreplan", type=Path, help="same run with replanning off")
    parser.add_argument("--ceiling", type=Path, help="ceiling_check JSON for the evaluated code")
    parser.add_argument("--spike", type=Path, help="spike summary CSV")
    parser.add_argument(
        "--questions", type=Path, default=Path("evaluation/benchmark/questions.json")
    )
    parser.add_argument("--out", type=Path, default=Path("docs/report"))
    args = parser.parse_args()

    cat_of = categories(args.questions)
    reachable = set(json.loads(args.ceiling.read_text())["reachable"]) if args.ceiling else None
    runs: dict[str, dict] = {}
    main_run = summarise(load_run(args.main), cat_of, reachable)
    runs["Main"] = main_run
    noreplan = None
    if args.noreplan:
        noreplan = summarise(load_run(args.noreplan), cat_of, reachable)
        runs["NoRep"] = noreplan

    (args.out / "generated").mkdir(parents=True, exist_ok=True)
    (args.out / "figures").mkdir(parents=True, exist_ok=True)
    write_numbers(args.out / "generated", runs)
    write_category_table(args.out / "generated", main_run, noreplan)
    if args.spike:
        write_spike_table(args.out / "generated", args.spike)
    write_time_figure(args.out, main_run, noreplan)
    for tag, s in runs.items():
        t = s["totals"]
        print(
            f"{tag:6s} questions passed {t['q']}/{t['n']}  attempts {t['a']}/{t['at']}  failed {s['failed_q']}"
        )


if __name__ == "__main__":
    main()
